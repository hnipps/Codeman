import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
import { chromium } from 'playwright';
const [, , demoDir, outDir] = process.argv;
const srv = http.createServer((q, s) => { const f = path.join(demoDir, q.url.split('?')[0]); if (!fs.existsSync(f)) { s.writeHead(404); return s.end(); } s.writeHead(200, { 'content-type': 'text/html' }); fs.createReadStream(f).pipe(s); });
await new Promise(r => srv.listen(0, '127.0.0.1', r));
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 900, height: 520 }, deviceScaleFactor: 1 });
const errors = []; page.on('pageerror', e => errors.push(String(e))); page.on('console', m => m.type() === 'error' && errors.push(m.text()));
await page.goto(`http://127.0.0.1:${srv.address().port}/demo.html`, { waitUntil: 'domcontentloaded' });
await page.waitForSelector('.xterm canvas', { timeout: 15000 });
await page.waitForTimeout(1500);
const btn = await page.locator('#hoverBtn').boundingBox();
await page.mouse.move(btn.x + 10, btn.y + 10);
await page.screenshot({ path: path.join(outDir, 'demo-before.png') });
await page.keyboard.press('Control+Shift+X');
await page.waitForSelector('#capture.on', { timeout: 10000 });
const term = await page.locator('#term').boundingBox(); const obj = await page.locator('.obj').boundingBox();
const loop = [[term.x + 5, term.y + 5], [term.x + 300, term.y + 5], [obj.x + obj.width + 10, obj.y + obj.height + 10], [term.x + 5, obj.y + obj.height + 10], [term.x + 5, term.y + 5]];
await page.mouse.move(...loop[0]); await page.mouse.down();
for (let i = 1; i < loop.length; i++) await page.mouse.move(...loop[i], { steps: 8 });
await page.mouse.up();
await page.fill('#noteText', 'FAIL line hides the expected value');
await page.screenshot({ path: path.join(outDir, 'demo-drawing.png') });
await page.click('#note button[type=submit]');
await page.waitForSelector('#result.on');
const r = await page.evaluate(async ({ term, btn, proto }) => {
  const { capture, files } = window.__lastCapture;
  const img = await new Promise(ok => { const i = new Image(); i.onload = () => ok(i); i.src = files['clean.png']; });
  const c = document.createElement('canvas'); c.width = img.width; c.height = img.height; const g = c.getContext('2d'); g.drawImage(img, 0, 0);
  const hex = (x, y) => '#' + [...g.getImageData(Math.round(x), Math.round(y), 1, 1).data].slice(0, 3).map(v => v.toString(16).padStart(2, '0')).join('');
  let termLit = 0; const d = g.getImageData(term.x, term.y, term.width, term.height).data; for (let i = 0; i < d.length; i += 4) if (d[i] + d[i + 1] + d[i + 2] > 60) termLit++;
  return { capture: { ...capture, path: { ...capture.path, points: capture.path.points.length + ' points' } }, cleanSize: [img.width, img.height], terminalLitPixels: termLit, hoverPixel: hex(btn.x + 3, btn.y + 3), protoPixel: hex(proto.x + 150, proto.y + 80), toastPixel: hex(img.width - 30, img.height - 25) };
}, { term, btn, proto: await page.locator('#proto').boundingBox() });
for (const [n, url] of Object.entries(await page.evaluate(() => window.__lastCapture.files))) fs.writeFileSync(path.join(outDir, n), Buffer.from(url.split(',')[1], 'base64'));
await page.screenshot({ path: path.join(outDir, 'demo-result.png'), fullPage: true });
console.log(JSON.stringify({ ...r, errors }, null, 2));
await browser.close(); srv.close();
